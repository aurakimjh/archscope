// Generates synthetic loopback traffic only. It does not write .halog files or
// run/install the original application. Record this PID with a licensed V7.6.4.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { createInterface } from "node:readline/promises";
import {
  startReferenceFixture,
  exerciseReferenceFixture,
} from "./http-reference-fixture.mjs";
const args = process.argv.slice(2);
let output = "",
  runNow = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--out") output = args[++i];
  else if (args[i] === "--run-now") runNow = true;
  else throw new Error("unknown fixture option");
}
if (!output) throw new Error("--out is required");
output = path.resolve(output);
if (path.extname(output).toLowerCase() === ".halog")
  throw new Error("expectations are JSON, not a legacy log");
await mkdir(path.dirname(output), { recursive: true });
const fixture = await startReferenceFixture();
try {
  console.log(`Synthetic fixture PID: ${process.pid}`);
  if (!runNow) {
    const reader = createInterface({
      input: process.stdin,
      output: process.stdout,
    });
    try {
      await reader.question(
        "Select this PID in the reference app, start recording, then press Enter. ",
      );
    } finally {
      reader.close();
    }
  }
  const expected = await exerciseReferenceFixture(fixture);
  await writeFile(output, JSON.stringify(expected, null, 2), {
    flag: "wx",
    mode: 0o600,
  });
  console.log(
    "Traffic complete. Stop the reference app and save the SAME capture as Native .halog and Full XML. No .halog was generated by this script.",
  );
} finally {
  await fixture.close();
}
